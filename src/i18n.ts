const DICTS: Record<Lang, Dict> = { ar, en };

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? DICTS.ar[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** Units for {max} in each message, so numbers print as "0.25 W" rather than "0.25". */
const MAX_UNIT: Record<string, string> = {
  'burn.resistor': 'W',
  'burn.lamp': 'W',
  'burn.speaker': 'W',
  'burn.buzzer': 'V',
  'burn.zener': 'W',
  'burn.transistor': 'W',
  'warn.resistorHot': 'W',
  'burn.fuse': 'A',
  'burn.led': 'A',
  'burn.diode': 'A',
  'warn.ledHigh': 'A',
  'burn.capVoltage': 'V',
};
const VAR_UNIT: Record<string, string> = { p: 'W', i: 'A', v: 'V' };

/** A doctor message with its numbers formatted. */
export function message(key: string, label: string, vars: Record<string, string | number> = {}): string {
  const out: Record<string, string | number> = { label };
  for (const [k, v] of Object.entries(vars)) {
    if (typeof v !== 'number') out[k] = v;
    else if (k === 'max') out[k] = fmt(v, MAX_UNIT[key] ?? '');
    else if (k in VAR_UNIT) out[k] = fmt(v, VAR_UNIT[k]);
    else out[k] = v;
  }
  return t(key, out);
}

export const nameOf = (o: { ar: string; en: string }): string => (lang === 'ar' ? o.ar : o.en);
